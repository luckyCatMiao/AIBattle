import { chromium } from '/tmp/pwtest/node_modules/playwright/index.mjs';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', e => console.log('ERR', e.message));
await page.goto('file:///workspace/game.html');
await page.waitForTimeout(300);
await page.keyboard.press('Enter');
await page.waitForTimeout(600);
await page.evaluate(() => { Game.spawnQueue.length = 0; Game.enemies.length = 0; Game.player.x = 900; Camera.x = 900 - 480/2; Camera.zoom = 2.6; Game.bannerT = 0; Game.waveState='idle'; Game.waveT=99; });
await page.waitForTimeout(500);
await page.keyboard.down('KeyD'); await page.waitForTimeout(420);
await page.screenshot({ path: '/workspace/test/pc_run.png' });
await page.keyboard.down('KeyJ'); 
await page.keyboard.press('KeyJ'); await page.waitForTimeout(70);
await page.screenshot({ path: '/workspace/test/pc_run_atk.png' });
await page.keyboard.up('KeyD');
await page.waitForTimeout(600);
await page.screenshot({ path: '/workspace/test/pc_after.png' });
await browser.close();
