import { chromium } from '/tmp/pwtest/node_modules/playwright/index.mjs';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', e => console.log('ERR', e.message));
await page.goto('file:///workspace/game.html');
await page.waitForTimeout(300);
await page.keyboard.press('Enter');
await page.waitForTimeout(800);
await page.evaluate(() => { Game.spawnQueue.length = 0; Game.enemies.forEach(e=>e.x = 900); });
await page.waitForTimeout(1200);
await page.screenshot({ path: '/workspace/test/z_idle.png' });
await page.keyboard.press('KeyJ'); await page.waitForTimeout(80);
await page.screenshot({ path: '/workspace/test/z_atk.png' });
await page.waitForTimeout(400);
await page.keyboard.down('KeyK'); await page.waitForTimeout(700);
await page.screenshot({ path: '/workspace/test/z_charge.png' });
await page.keyboard.up('KeyK'); await page.waitForTimeout(70);
await page.screenshot({ path: '/workspace/test/z_release.png' });
await browser.close();
