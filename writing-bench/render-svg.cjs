'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const { Resvg } = require('@resvg/resvg-js');
const [input, output] = process.argv.slice(2);
if (!input || !output) throw Error('Usage: node render-svg.cjs input.svg output.png');
const normalized=spawnSync(path.join(__dirname,'.venv','Scripts','python.exe'),[path.join(__dirname,'normalize-svg.py'),input],{encoding:'utf8',timeout:10000,maxBuffer:8*1024*1024,windowsHide:true});
if(normalized.status!==0)throw Error(normalized.stderr||'SVG compatibility normalization failed');
const {svg:source,compatibility_adjustments}=JSON.parse(normalized.stdout);
const options = {background:'#ffffff',font:{loadSystemFonts:true,defaultFontFamily:'Microsoft YaHei'},logLevel:'error'};
const probe = new Resvg(source, options);
if (!(probe.width>0 && probe.height>0) || Math.max(probe.width/probe.height,probe.height/probe.width)>20) throw Error('Unsupported artwork aspect ratio');
const longestIsWidth = probe.width >= probe.height;
const renderer = new Resvg(source,{...options,fitTo:{mode:longestIsWidth?'width':'height',value:1600}});
if (renderer.imagesToResolve().length) throw Error('External image resources are not supported');
const image = renderer.render();
fs.writeFileSync(output,image.asPng());
process.stdout.write(JSON.stringify({width:image.width,height:image.height,bytes:fs.statSync(output).size,compatibility_adjustments}));
