"""Submission entry point: reads observations on stdin, writes action windows.

This file is generated by build_agent.py from engine_py.py + planner.py +
brain_py.py + this main loop, so that the submitted program is a single
self-contained file.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from brain_py import Brain


def _neutral():
    return {"move": 0.0, "jump": False, "swing": 0, "charge": False, "sprint": False}


def main():
    try:
        sys.stdin.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    try:
        sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    except Exception:
        pass
    brain = Brain()
    out = sys.stdout
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            obs = json.loads(line)
        except Exception:
            obs = {}
        try:
            frames = brain.act(obs)
            if not isinstance(frames, list) or len(frames) != 10:
                raise ValueError("bad window")
            payload = []
            for f in frames:
                if not isinstance(f, dict):
                    raise ValueError("bad frame")
                payload.append([{
                    "move": float(f.get("move", 0.0)),
                    "jump": bool(f.get("jump", False)),
                    "swing": int(f.get("swing", 0)),
                    "charge": bool(f.get("charge", False)),
                    "sprint": bool(f.get("sprint", False)),
                }])
        except Exception:
            payload = [[_neutral()] for _ in range(10)]
        out.write(json.dumps({"inputs": payload}, separators=(",", ":")) + "\n")
        out.flush()


if __name__ == "__main__":
    main()
