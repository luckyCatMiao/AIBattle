"""Bundle the physics/planner/brain modules into a single agent.py.

The bundled file must stay byte-for-byte runnable with `python3 agent.py`
(stdin/stdout protocol) and must not import any local module.
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "agent.py")

HEADER = '''"""Single-file badminton agent for the arena (generated by build_agent.py).

Reads one JSON observation per line on stdin and writes one JSON input window
per line on stdout.  Contains a line-by-line Python port of the public physics
(catalog.js / simulation.js) used for forward planning, plus the planner and
the decision brain.
"""
import json
import math
import os
import sys

'''


def strip_imports(src, names):
    lines = []
    skip_block = False
    for line in src.splitlines():
        s = line.strip()
        if skip_block:
            if s.endswith(")"):
                skip_block = False
            continue
        if s in names:
            continue
        if s.startswith("from planner import"):
            if "(" in s and ")" not in s:
                skip_block = True
            continue
        if s.startswith("import engine_py") or s.startswith("import planner"):
            continue
        if s.startswith("sys.path.insert"):
            continue
        lines.append(line)
    return "\n".join(lines)


def main():
    parts = [HEADER]
    eng = io.open(os.path.join(HERE, "engine_py.py"), encoding="utf-8").read()
    eng = eng.replace('"""Python port', '"""Python port', 1)
    # drop the module docstring's import-free body is fine; just remove its own docstring
    parts.append("# ===================== physics (engine_py) =====================\n")
    parts.append(strip_imports(eng, {"import math"}))
    parts.append("\n# module alias so the ported modules can keep using E.*\n"
                 "E = sys.modules[__name__]\n")
    parts.append("\n# ===================== planner =====================\n")
    plan = io.open(os.path.join(HERE, "planner.py"), encoding="utf-8").read()
    parts.append(strip_imports(plan, {"import math"}))
    parts.append("\n# ===================== brain =====================\n")
    brain = io.open(os.path.join(HERE, "brain_py.py"), encoding="utf-8").read()
    parts.append(strip_imports(brain, {"import math", "import os", "import sys"}))
    parts.append("\n# ===================== main loop =====================\n")
    main_src = io.open(os.path.join(HERE, "agent_main.py"), encoding="utf-8").read()
    # strip the docstring and the imports / sys.path / from brain_py import
    main_src = re.sub(r'^"""[\s\S]*?"""\n', "", main_src, count=1)
    main_src = strip_imports(main_src, {"import json", "import os", "import sys",
                                        "from brain_py import Brain"})
    parts.append(main_src)
    text = "\n".join(parts)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT, len(text), "bytes")


if __name__ == "__main__":
    main()
